# Database
# https://docs.djangoproject.com/en/6.1/ref/settings/#databases
#
# Django usa la MISMA base de datos MariaDB/MySQL que la aplicación Java
# (Spring Boot). Las tablas de Java las gestiona Hibernate: los modelos de la
# app `inmovision_java` son managed = False y Django nunca las modifica.
# Las tablas propias de Django (usuarios, sesiones, revisión de publicaciones)
# sí las crea `python manage.py migrate`.

DB_ENGINE = os.environ.get("DB_ENGINE", "mysql").strip().lower()

if DB_ENGINE == "mysql":
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.mysql',
            'NAME': os.environ.get("DB_NAME", "inmovision3d"),
            'USER': _requerida("DB_USER"),
            'PASSWORD': os.environ.get("DB_PASSWORD", ""),
            'HOST': os.environ.get("DB_HOST", "127.0.0.1"),
            'PORT': os.environ.get("DB_PORT", "3306"),
            # Java guarda las fechas (LocalDateTime) en hora local de Bogotá,
            # sin zona horaria. Así Django las lee y las muestra bien.
            'TIME_ZONE': 'America/Bogota',
            'OPTIONS': {
                'charset': 'utf8mb4',
                'init_command': "SET sql_mode='STRICT_TRANS_TABLES'",
            },
        }
    }
elif DB_ENGINE == "sqlite":
    # Solo para pruebas rápidas sin MariaDB: NO muestra los datos reales de Java.
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }
    }
else:
    raise ImproperlyConfigured(
        "DB_ENGINE debe ser 'mysql' o 'sqlite' "
        f"(valor recibido: '{DB_ENGINE}')."
    )


